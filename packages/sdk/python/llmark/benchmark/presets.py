    "## 4. API接口定义\n\n"
    "### 4.1 认证机制\n\n"
    "**管理后台接口认证（JWT Bearer Token）**\n"
    "- Token类型：Access Token + Refresh Token\n"
    "- Access Token：JWT格式，HS256签名，有效期2小时\n"
    "- Refresh Token：JWT格式，HS256签名，有效期7天，单次使用\n"
    "- Token内容：user_id、role、permissions、iat、exp\n"
    "- 请求头：Authorization: Bearer <access_token>\n"
    "- 刷新机制：Access Token过期前5分钟，用Refresh Token换取新Token对\n"
    "- 安全：Refresh Token存储于HttpOnly Cookie，防止XSS窃取\n\n"
    "**客户端接口认证（API Key + 请求签名）**\n"
    "- API Key：32位随机字符串，由管理后台生成并分配\n"
    "- 请求签名：HMAC-SHA256(api_secret, timestamp + method + path + body)\n"
    "- 时间戳：Unix时间戳（秒），与服务器时间差不得超过300秒（防重放）\n"
    "- 请求头：\n"
    "  - X-API-Key: <api_key>\n"
    "  - X-Timestamp: <timestamp>\n"
    "  - X-Signature: <signature>\n"
    "  - X-Request-ID: <uuid>（用于链路追踪）\n\n"
    "**WebSocket连接认证**\n"
    "- 握手阶段：HTTP Upgrade请求携带JWT Token\n"
    "- 验证通过后：服务端生成session_id，绑定到connection\n"
    "- 后续消息：通过session_id验证，无需重复认证\n"
    "- 心跳机制：客户端每30秒发送ping，服务端回复pong，"
    "连续3次未收到ping则断开连接\n\n"
