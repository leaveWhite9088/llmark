    "## 5. 核心模块详细设计\n\n"
    "### 5.1 对话引擎状态机\n\n"
    "会话生命周期状态定义：\n"
    "```\n"
    "INIT -> AI_CHATTING -> [TRANSFERRING] -> HUMAN_CHATTING -> CLOSED\n"
    "         |                              |\n"
    "         v                              v\n"
    "      CLOSED（超时）               CLOSED（超时/关闭）\n"
    "```\n\n"
    "状态转换条件与触发事件：\n\n"
    "**INIT -> AI_CHATTING**\n"
    "- 触发条件：会话初始化完成（/chat/init调用成功）\n"
    "- 执行动作：发送欢迎语、加载用户画像、初始化对话上下文\n"
    "- 异常处理：初始化失败（如用户token无效）直接返回错误，不进入状态机\n\n"
