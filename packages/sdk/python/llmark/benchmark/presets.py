    "- 敏感词脱敏（替换为*）\n"
    "- 输出：清洗后的标准文本\n\n"
    "**Layer 2：精确匹配**\n"
    "- 查询知识库question字段的完全匹配\n"
    "- 查询相似问法列表的完全匹配\n"
    "- 命中则直接返回，confidence=1.0\n"
    "- 耗时目标：<10ms\n\n"
    "**Layer 3：规则匹配**\n"
    "- 基于正则表达式和关键词的规则引擎\n"
