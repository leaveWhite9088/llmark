    "## 10. 灾难恢复方案\n\n"
    "### 10.1 目标\n"
    "- RPO（恢复点目标）：<5分钟\n"
    "- RTO（恢复时间目标）：<30分钟\n"
    "- 数据持久性：99.9999999%（11个9）\n\n"
    "### 10.2 容灾架构\n\n"
    "**同城双活**\n"
    "- 主可用区：杭州可用区G\n"
    "- 备可用区：杭州可用区H\n"
    "- 数据同步：RDS主从实时同步，Redis跨可用区复制\n"
    "- 流量切换：DNS加权轮询，故障时自动切换\n\n"
    "**异地灾备**\n"
    "- 灾备区域：深圳\n"
    "- RDS：异步复制，延迟<1秒\n"
    "- 对象存储：跨区域冗余（OSS跨区域复制）\n"
    "- 切换：人工决策，RTO约30分钟\n\n"
    "### 10.3 故障场景与恢复\n\n"
    "**场景1：单Pod故障**\n"
    "- 检测：Liveness探针失败\n"
    "- 自动：K8s重启Pod，约30秒\n"
    "- 影响：该Pod上的会话断开，客户端自动重连\n"
    "- 恢复：无需人工介入\n\n"
    "**场景2：单服务故障**\n"
    "- 检测：Readiness探针失败 + 告警\n"
    "- 自动：HPA扩容新Pod，Ingress移除异常Endpoint\n"
    "- 影响：服务降级（如chat-engine故障时，所有会话直接转人工）\n"
    "- 恢复：服务恢复后自动接入流量\n\n"
    "**场景3：数据库主库故障**\n"
    "- 检测：RDS自动故障检测\n"
    "- 自动：RDS自动主从切换（约30秒）\n"
    "- 影响：写操作中断30秒，读操作不受影响\n"
    "- 恢复：原主库恢复后作为新从库加入\n\n"
    "**场景4：全区域故障**\n"
    "- 检测：多可用区同时不可用\n"
    "- 人工：决策切换至深圳灾备\n"
    "- 操作：\n"
    "  1. 修改DNS指向深圳入口\n"
    "  2. 提升深圳RDS从库为主库\n"
    "  3. 启动深圳K8s集群服务\n"
    "  4. 验证服务可用性\n"
    "- 影响：服务中断约30分钟\n"
    "- 恢复：杭州恢复后，数据同步追平后切回\n\n"
    "### 10.4 备份验证\n"
    "- 每月一次备份恢复演练\n"
    "- 验证数据完整性（行数校验、抽样比对）\n"
    "- 验证恢复时间（RTO）\n"
    "- 演练报告存档，缺陷跟踪修复\n\n"
