    "- 规则优先级可配置，支持动态热更新\n"
    "- 命中则返回，confidence=0.95\n"
    "- 耗时目标：<20ms\n\n"
    "**Layer 4：语义匹配（向量检索）**\n"
    "- 将用户query转为1024维向量（BGE-M3模型）\n"
    "- 在Milvus中检索Top10相似知识点\n"
    "- 计算余弦相似度，筛选相似度>0.75的候选\n"
    "- 返回候选列表及相似度分数\n"
    "- 耗时目标：<100ms\n\n"
    "**Layer 5：大模型判断（LLM Rerank）**\n"
    "- 将Top5候选 + 用户query输入LLM\n"
    "- LLM输出：最匹配的knowledge_id、置信度（0.0-1.0）、理由\n"
    "- Prompt工程：包含 few-shot 示例、输出格式约束、安全提示\n"
    "- 超时控制：3秒，超时则使用Layer 4结果\n"
    "- 降级策略：LLM服务不可用时，取Layer 4相似度最高项\n\n"
    "**结果路由**\n"
    "- confidence > 0.8：直接返回答案\n"
    "- confidence 0.6-0.8：返回答案，前缀标注'以下信息仅供参考'\n"
    "- confidence < 0.6：触发拒识，进入转人工流程\n\n"
    "### 5.3 知识库向量检索\n\n"
    "**文本向量化**\n"
    "- 模型：BAAI/bge-m3（1024维）\n"
    "- 部署：独立推理服务（Python + ONNX Runtime），GPU加速（T4）\n"
    "- 批处理：支持批量向量化，单次最多100条\n"
    "- 缓存：向量结果缓存于Redis，TTL 24小时\n"
    "- 性能：单条<50ms，批量100条<500ms\n\n"
    "**索引策略**\n"
    "- 按brand_id分Collection（3个品牌 + 1个通用 = 4个Collection）\n"
    "- 索引类型：IVF_FLAT\n"
    "- 参数：nlist=1024（根据数据量动态调整）\n"
    "- 距离度量：COSINE\n\n"
    "**检索参数**\n"
    "- nprobe=128（精度与性能平衡）\n"
    "- 返回Top10\n"
    "- 重排序：使用Cross-Encoder模型对Top10重新打分，取Top5\n"
    "- 过滤条件：status=1（仅启用状态）\n\n"
    "**增量更新**\n"
    "- 新知识点写入后，异步向量化（RabbitMQ消息队列）\n"
    "- 向量化完成后写入Milvus，延迟<5秒\n"
    "- 批量导入时，使用Milvus Bulk Insert API，提升写入性能\n\n"
    "### 5.4 会话分配算法\n\n"
    "**加权评分模型**\n"
    "对每个在线且状态为'在线'的客服计算综合得分：\n"
    "```\n"
    "score = skill_match * 0.40 + (1 - load_rate) * 0.30 + \n"
    "        avg_rating / 5.0 * 0.20 + vip_priority * 0.10\n"
    "```\n\n"
    "**因子详解**\n"
    "- skill_match：技能组匹配度。会话所需技能组与客服技能组的Jaccard相似度\n"
    "- load_rate：当前负载率 = current_sessions / max_concurrent\n"
    "- avg_rating：该客服近30天平均客户评分（1-5分，归一化到0-1）\n"
    "- vip_priority：VIP客户优先系数。VIP0=0, VIP1=0.2, VIP2=0.4, VIP3=0.6, VIP4=0.8, VIP5=1.0\n\n"
    "**分配流程**\n"
    "1. 筛选：状态=在线 且 current_sessions < max_concurrent 的客服\n"
    "2. 计算：对筛选后的客服计算score\n"
    "3. 排序：按score降序排列\n"
    "4. 分配：将会话分配给score最高的客服\n"
    "5. 更新：客服current_sessions + 1\n\n"
    "**权重重算**\n"
    "- 每30秒重新计算一次所有客服的score\n"
    "- 客服状态变更时立即重算\n"
    "- 新会话进入时实时分配\n\n"
    "**VIP特殊处理**\n"
    "- VIP3以上客户：优先分配主管（role=1）或资深客服（avg_rating>=4.5）\n"
    "- 如无合适客服，VIP客户插队至队列头部\n"
    "- VIP客户排队超3分钟自动触发主管告警\n\n"
    "## 6. 安全设计方案\n\n"
    "### 6.1 认证与授权\n\n"
    "**JWT认证细节**\n"
    "- 算法：HS256（HMAC-SHA256）\n"
    "- 密钥：256位随机字符串，存储于KMS，每季度轮换\n"
    "- Payload：\n"
    "  - sub：用户ID\n"
    "  - role：角色编码\n"
    "  - permissions：权限列表（如 ['knowledge:read', 'knowledge:write']）\n"
    "  - iat：签发时间\n"
    "  - exp：过期时间（iat + 2小时）\n"
    "  - jti：Token唯一标识（用于黑名单）\n"
    "- Refresh Token机制：\n"
    "  - 有效期7天\n"
    "  - 单次使用（使用后立即失效，发放新Token对）\n"
    "  - 存储于Redis，键格式：refresh:{jti}，TTL 7天\n"
    "  - 被盗检测：同一Refresh Token被使用两次时，吊销该用户所有Token\n\n"
    "**API Key认证细节**\n"
    "- API Key：32位随机字符串，前缀yz_（如 yz_a1b2c3d4e5f6...）\n"
    "- API Secret：64位随机字符串，仅生成时展示一次\n"
    "- 签名算法：HMAC-SHA256(api_secret, timestamp + method + path + sha256(body))\n"
    "- 时间戳校验：|server_timestamp - request_timestamp| <= 300秒\n"
    "- 重放防护：Redis记录已使用的(timestamp, nonce)组合，TTL 300秒\n\n"
    "**WebSocket认证**\n"
    "- 握手阶段：HTTP Upgrade请求头携带Authorization: Bearer <jwt>\n"
    "- 验证：解析JWT，校验签名、过期时间、权限\n"
    "- 通过：生成session_id（UUID v4），建立WebSocket连接\n"
    "- 拒绝：返回HTTP 401，关闭连接\n"
    "- 后续消息：通过session_id从Redis获取用户信息，无需重复解析JWT\n\n"
    "**密码策略**\n"
    "- 最小长度：8位\n"
    "- 复杂度：必须包含大写字母、小写字母、数字、特殊字符各至少1个\n"
    "- 历史密码：禁止重复使用最近5次密码\n"
    "- 更换周期：90天强制更换\n"
    "- 传输：前端使用RSA公钥加密后传输，服务端私钥解密后bcrypt哈希存储\n\n"
