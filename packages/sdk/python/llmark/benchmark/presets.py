    "- 位置：共享Redis集群\n"
    "- 数据：会话状态、用户画像、限流计数、知识库元数据\n"
    "- TTL：会话状态24小时、用户画像1小时、限流计数1分钟\n"
    "- 序列化：JSON + Snappy压缩\n"
    "- 命中率目标：>=80%\n\n"
    "**L3缓存：CDN缓存**\n"
    "- 位置：阿里云CDN边缘节点\n"
